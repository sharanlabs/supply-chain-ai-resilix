import { describe, expect, it } from "vitest";
import { runAtlas } from "@/lib/agents/actionops/atlas";
import { runSentinel } from "@/lib/agents/actionops/sentinel";
import { getActionOpsScenario, type ActionOpsScenario } from "@/lib/data/actionops-scenarios";
import { ingestSeed } from "@/lib/ingest/seed-suppliers";
import type { ActionOpsContext } from "@/lib/agents/actionops/types";
import type { Supplier } from "@/lib/schemas";

// D.2 Atlas: the deterministic exposure model (risk tier + lead time), the
// Sentinel-handoff firewall (a misclassified threat -> rejected, not silently
// mis-exposed), the sector firewall (off-taxonomy -> OTHER_UNMAPPED), and the
// zero-exposure control. The scores are HAND-DERIVED below (never generated by
// running the formula -- the F lesson), pinned by stable seed name so a formula OR
// a seed change fails loudly.

const BASE_DATE = "2026-06-18T12:00:00.000Z";

function hormuzContext(): ActionOpsContext {
  return {
    scenario: getActionOpsScenario(),
    signals: [],
    suppliers: ingestSeed().suppliers,
    baseDateIso: BASE_DATE
  };
}

// score = RISK_TIER_BASE[tier] + clamp(leadDays - 30, 0, 30); base CRITICAL 55 /
// HIGH 40 / MEDIUM 25 / LOW 12. Worked: Abu Chemical Partners 078 = CRITICAL(55) +
// clamp(44-30)=14 = 69. (tier/lead read from data/seed/us-suppliers.seed.csv.)
const EXPECTED_SCORES: Record<string, number> = {
  "Abu Chemical Partners 078": 69, // AE CRITICAL 44 -> 55 + 14
  "Eastern Energy Partners 094": 68, // SA CRITICAL 43 -> 55 + 13
  "Al Energy Solutions 096": 59, // KW HIGH 49 -> 40 + 19
  "Ras Energy Systems 095": 56, // QA HIGH 46 -> 40 + 16
  "Eastern Chemical Group 076": 54, // SA HIGH 44 -> 40 + 14
  "Jubail Chemical Manufacturing 077": 40, // SA MEDIUM 45 -> 25 + 15
  "Jebel Energy Group 092": 34, // AE MEDIUM 39 -> 25 + 9
  "Ras Chemical Systems 079": 24, // QA LOW 42 -> 12 + 12
  "Abu Energy Manufacturing 093": 22 // AE LOW 40 -> 12 + 10
};

describe("Atlas exposure model (D.2, deterministic, key-OFF)", () => {
  it("scores the nine Gulf suppliers from risk tier + lead time (hand-pinned)", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    const { exposureResults, dataGaps } = runAtlas(ctx, threatCard);

    expect(exposureResults).toHaveLength(9);
    expect(dataGaps).toEqual([]); // healthy match -> no gap

    for (const exposure of exposureResults) {
      const expected = EXPECTED_SCORES[exposure.supplierName];
      expect(expected, `unexpected supplier ${exposure.supplierName}`).toBeDefined();
      expect(exposure.exposureScore, exposure.supplierName).toBe(expected);
    }
    // Exactly the nine hand-pinned suppliers -- no miss, no extra.
    expect(new Set(exposureResults.map((e) => e.supplierName))).toEqual(
      new Set(Object.keys(EXPECTED_SCORES))
    );
  });

  it("ranks exposures by score descending, deterministically", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    const { exposureResults } = runAtlas(ctx, threatCard);

    const scores = exposureResults.map((e) => e.exposureScore);
    expect(scores).toEqual([...scores].sort((a, b) => b - a));
    expect(scores[0]).toBe(69); // Abu Chemical Partners 078 leads
  });

  it("passes the handoff when the matched set fits the threat scope (Hormuz)", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Control for the rejection test below: the genuine Hormuz handoff, whose Gulf
    // match IS within the Strait of Hormuz scope, is NOT rejected.
    const { exposureResults, agentRun } = runAtlas(ctx, threatCard);
    expect(exposureResults).toHaveLength(9);
    expect(agentRun.validationStatus).toBe("PASS");
  });

  it("REJECTS a misclassified Sentinel handoff: matched suppliers outside the threat scope", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Corrupt ONLY the handoff: same Gulf match, but the threat now claims a chokepoint
    // whose affected scope EXCLUDES the Gulf. This corruption changes what the correct
    // exposures should be (none, for a Malacca event), so Atlas passing it through would
    // be a real bug -- the teeth are non-vacuous. Atlas must catch the threat<->match
    // disagreement and fail closed.
    const misclassified = {
      ...threatCard,
      location: { ...threatCard.location, chokepoint: "Strait of Malacca" }
    };
    const { exposureResults, dataGaps, agentRun } = runAtlas(ctx, misclassified);

    expect(exposureResults).toEqual([]);
    expect(dataGaps.join(" ")).toMatch(/outside the affected scope/i);
    expect(dataGaps.join(" ")).toMatch(/misclassification/i);
    expect(agentRun.validationStatus).toBe("FAIL");
  });

  it("holds a supplier with an off-taxonomy sector as OTHER_UNMAPPED (never force-fit)", () => {
    const base = hormuzContext();
    // Corrupt one matched supplier's sector to a value outside the closed SectorSchema.
    const suppliers = base.suppliers.map((s) =>
      s.name === "Abu Chemical Partners 078"
        ? { ...s, sector: "BANANAS" as unknown as Supplier["sector"] }
        : s
    );
    const ctx: ActionOpsContext = { ...base, suppliers };
    const { threatCard } = runSentinel(ctx);
    const { exposureResults } = runAtlas(ctx, threatCard);

    const corrupted = exposureResults.find(
      (e) => e.supplierName === "Abu Chemical Partners 078"
    );
    expect(corrupted?.sector).toBe("OTHER_UNMAPPED");
    // A clean supplier keeps its valid closed-vocab sector.
    const clean = exposureResults.find(
      (e) => e.supplierName === "Eastern Energy Partners 094"
    );
    expect(clean?.sector).toBe("ENERGY");
  });

  it("declares no-direct-exposure for a genuinely unmatched event (zero-exposure control)", () => {
    const base = hormuzContext();
    // A scenario whose match targets a country with no supplier in the base.
    const emptyScenario: ActionOpsScenario = {
      ...base.scenario,
      id: "SCN-EMPTY-TEST",
      match: { countries: ["ZZ"] }
    };
    const ctx: ActionOpsContext = { ...base, scenario: emptyScenario };
    const { threatCard } = runSentinel(ctx);
    const { exposureResults, dataGaps } = runAtlas(ctx, threatCard);

    expect(exposureResults).toEqual([]);
    expect(dataGaps.join(" ")).toMatch(/no direct exposure/i);
  });
});
