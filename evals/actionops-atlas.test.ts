import { describe, expect, it } from "vitest";
import { runActionOpsAgents } from "@/lib/agents/actionops";
import { runAtlas } from "@/lib/agents/actionops/atlas";
import { runActionOpsGatekeeper } from "@/lib/agents/actionops/gatekeeper";
import { runSentinel } from "@/lib/agents/actionops/sentinel";
import { getActionOpsScenario, type ActionOpsScenario } from "@/lib/data/actionops-scenarios";
import { ingestSeed } from "@/lib/ingest/seed-suppliers";
import { fetchPublicSignals } from "@/lib/signals/fetchers";
import type { ActionOpsContext } from "@/lib/agents/actionops/types";
import type { Supplier } from "@/lib/schemas";

// D.2 Atlas: the deterministic exposure model (risk tier + lead time), the
// Sentinel-handoff firewall (a misclassified threat -> rejected, not silently
// mis-exposed), the sector firewall (off-taxonomy -> OTHER_UNMAPPED), and the
// zero-exposure control. The scores are HAND-DERIVED below (never generated by
// running the formula -- the F lesson), pinned by stable seed name so a formula OR
// a seed change fails loudly.

const BASE_DATE = "2026-06-18T12:00:00.000Z";

function hormuzContext(): ActionOpsContext {
  return {
    scenario: getActionOpsScenario(),
    signals: [],
    suppliers: ingestSeed().suppliers,
    baseDateIso: BASE_DATE
  };
}

// score = RISK_TIER_BASE[tier] + clamp(leadDays - 30, 0, 30) + (singleSource ? 12 : 0);
// base CRITICAL 55 / HIGH 40 / MEDIUM 25 / LOW 12. P1 single-source is DECOUPLED from tier
// (the guidelines-monitor Kraljic correction): single-source = deliberately-sole-sourced
// (Abu Chemical 078, Ras Energy 095) OR no-qualified-alternate; everyone else is dual-sourced
// (incl. CRITICAL Eastern Energy 094 -- the resilient norm). So the +12 penalty now
// discriminates WITHIN a tier: single-source 078 (81) outscores dual-sourced critical 094
// (68), and single-source 095 (68) outscores dual-sourced high 096 (59). Worked: Abu Chemical
// Partners 078 = CRITICAL(55) + clamp(44-30)=14 + single-source(12) = 81. (tier/lead from
// data/seed/us-suppliers.seed.csv; backup status from linkBackupSuppliers.)
const EXPECTED_SCORES: Record<string, number> = {
  "Abu Chemical Partners 078": 81, // AE CRITICAL 44 single-source -> 55 + 14 + 12
  "Eastern Energy Partners 094": 68, // SA CRITICAL 43 dual-sourced -> 55 + 13 + 0
  "Ras Energy Systems 095": 68, // QA HIGH 46 single-source -> 40 + 16 + 12
  "Al Energy Solutions 096": 59, // KW HIGH 49 dual-sourced -> 40 + 19 + 0
  "Eastern Chemical Group 076": 54, // SA HIGH 44 dual-sourced -> 40 + 14 + 0
  "Jubail Chemical Manufacturing 077": 40, // SA MEDIUM 45 dual-sourced -> 25 + 15 + 0
  "Jebel Energy Group 092": 34, // AE MEDIUM 39 dual-sourced -> 25 + 9 + 0
  "Ras Chemical Systems 079": 24, // QA LOW 42 dual-sourced -> 12 + 12 + 0
  "Abu Energy Manufacturing 093": 22 // AE LOW 40 dual-sourced -> 12 + 10 + 0
};

// P1 single-source + recoveryDays per Gulf supplier. singleSource is true ONLY for the two
// deliberately-sole-sourced lanes (078, 095) -- decoupled from tier. Hormuz is a
// CHOKEPOINT_CLOSURE (a TRANSIT disruption), so recoveryDays = standardLeadTimeDays +
// (singleSource ? 14 : 0) -- no site-restoration band. Hand-derived, independent of the producer.
const EXPECTED_SINGLE_SOURCE: Record<string, { singleSource: boolean; recoveryDays: number }> = {
  "Abu Chemical Partners 078": { singleSource: true, recoveryDays: 58 }, // 44 + 14
  "Ras Energy Systems 095": { singleSource: true, recoveryDays: 60 }, // 46 + 14
  "Eastern Energy Partners 094": { singleSource: false, recoveryDays: 43 }, // dual-sourced
  "Al Energy Solutions 096": { singleSource: false, recoveryDays: 49 }, // dual-sourced
  "Eastern Chemical Group 076": { singleSource: false, recoveryDays: 44 }, // dual-sourced
  "Jubail Chemical Manufacturing 077": { singleSource: false, recoveryDays: 45 }, // dual-sourced
  "Jebel Energy Group 092": { singleSource: false, recoveryDays: 39 }, // dual-sourced
  "Ras Chemical Systems 079": { singleSource: false, recoveryDays: 42 }, // dual-sourced
  "Abu Energy Manufacturing 093": { singleSource: false, recoveryDays: 40 } // dual-sourced
};

describe("Atlas exposure model (D.2, deterministic, key-OFF)", () => {
  it("scores the nine Gulf suppliers from risk tier + lead time (hand-pinned)", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    const { exposureResults, dataGaps } = runAtlas(ctx, threatCard);

    expect(exposureResults).toHaveLength(9);
    expect(dataGaps).toEqual([]); // healthy match -> no gap

    for (const exposure of exposureResults) {
      const expected = EXPECTED_SCORES[exposure.supplierName];
      expect(expected, `unexpected supplier ${exposure.supplierName}`).toBeDefined();
      expect(exposure.exposureScore, exposure.supplierName).toBe(expected);
    }
    // Exactly the nine hand-pinned suppliers -- no miss, no extra.
    expect(new Set(exposureResults.map((e) => e.supplierName))).toEqual(
      new Set(Object.keys(EXPECTED_SCORES))
    );
  });

  it("ranks exposures by score descending, deterministically", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    const { exposureResults } = runAtlas(ctx, threatCard);

    const scores = exposureResults.map((e) => e.exposureScore);
    expect(scores).toEqual([...scores].sort((a, b) => b - a));
    expect(scores[0]).toBe(81); // Abu Chemical Partners 078 leads (single-source CRITICAL)
  });

  it("flags single-source suppliers and sets TTR (recoveryDays), hand-pinned", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    const { exposureResults } = runAtlas(ctx, threatCard);

    for (const exposure of exposureResults) {
      const expected = EXPECTED_SINGLE_SOURCE[exposure.supplierName];
      expect(expected, `unexpected supplier ${exposure.supplierName}`).toBeDefined();
      expect(exposure.singleSource, `${exposure.supplierName} singleSource`).toBe(
        expected.singleSource
      );
      expect(exposure.recoveryDays, `${exposure.supplierName} recoveryDays`).toBe(
        expected.recoveryDays
      );
      // The rationale surfaces the status in prose for the war-room read, tier-token first.
      expect(exposure.rationale).toMatch(
        expected.singleSource ? /single-source \(no qualified backup\)/ : /qualified backup on file/
      );
    }

    // The penalty DISCRIMINATES WITHIN a tier (the guidelines-monitor fix -- single-source is
    // decoupled from tier, so it is not collinear with the base). 2 single-source / 7 covered.
    const single = exposureResults.filter((e) => e.singleSource);
    const covered = exposureResults.filter((e) => !e.singleSource);
    expect(single.length).toBe(2);
    expect(covered.length).toBe(7);

    const byName = new Map(exposureResults.map((e) => [e.supplierName, e]));
    // Two CRITICAL suppliers, one single-source one not -> the penalty SEPARATES them (it
    // would be collinear/invisible if single-source tracked the tier).
    const critSingle = byName.get("Abu Chemical Partners 078")!; // CRITICAL, single-source
    const critDual = byName.get("Eastern Energy Partners 094")!; // CRITICAL, dual-sourced
    expect(critSingle.singleSource).toBe(true);
    expect(critDual.singleSource).toBe(false);
    expect(critSingle.exposureScore).toBeGreaterThan(critDual.exposureScore); // 81 > 68
    // And a single-source HIGH supplier can reach a dual-sourced CRITICAL's exposure.
    expect(byName.get("Ras Energy Systems 095")!.exposureScore).toBe(critDual.exposureScore); // 68 == 68
  });

  it("makes recoveryDays disruption-type-aware: a SITE-LOSS event adds a restoration band", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Same Gulf match + Hormuz chokepoint scope, but reclassify the event as a SITE-LOSS type
    // (a supplier insolvency): recovery now runs MONTHS longer than a transit lead time -- the
    // gap a flat lead-time TTR had (the guidelines-monitor finding). +60 restoration band.
    const bankruptcy = { ...threatCard, eventType: "SUPPLIER_BANKRUPTCY" };
    const byName = new Map(
      runAtlas(ctx, bankruptcy).exposureResults.map((e) => [e.supplierName, e])
    );
    expect(byName.get("Abu Chemical Partners 078")!.recoveryDays).toBe(118); // 44 + 60 + single 14
    expect(byName.get("Eastern Energy Partners 094")!.recoveryDays).toBe(103); // 43 + 60, dual-sourced

    // Control: the TRANSIT Hormuz event (CHOKEPOINT_CLOSURE) carries NO restoration band.
    const transit = new Map(
      runAtlas(ctx, threatCard).exposureResults.map((e) => [e.supplierName, e])
    );
    expect(transit.get("Abu Chemical Partners 078")!.recoveryDays).toBe(58); // 44 + 14 only
  });

  it("passes the handoff when the matched set fits the threat scope (Hormuz)", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Control for the rejection test below: the genuine Hormuz handoff, whose Gulf
    // match IS within the Strait of Hormuz scope, is NOT rejected.
    const { exposureResults, agentRun } = runAtlas(ctx, threatCard);
    expect(exposureResults).toHaveLength(9);
    expect(agentRun.validationStatus).toBe("PASS");
  });

  it("REJECTS a misclassified Sentinel handoff: matched suppliers outside the threat scope", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Corrupt ONLY the handoff: same Gulf match, but the threat now claims a chokepoint
    // whose affected scope EXCLUDES the Gulf. This corruption changes what the correct
    // exposures should be (none, for a Malacca event), so Atlas passing it through would
    // be a real bug -- the teeth are non-vacuous. Atlas must catch the threat<->match
    // disagreement and fail closed.
    const misclassified = {
      ...threatCard,
      location: { ...threatCard.location, chokepoint: "Strait of Malacca" }
    };
    const { exposureResults, dataGaps, agentRun } = runAtlas(ctx, misclassified);

    expect(exposureResults).toEqual([]);
    expect(dataGaps.join(" ")).toMatch(/outside the affected scope/i);
    expect(dataGaps.join(" ")).toMatch(/misclassification/i);
    expect(agentRun.validationStatus).toBe("FAIL");
  });

  it("holds a supplier with an off-taxonomy sector as OTHER_UNMAPPED (never force-fit)", () => {
    const base = hormuzContext();
    // Corrupt one matched supplier's sector to a value outside the closed SectorSchema.
    const suppliers = base.suppliers.map((s) =>
      s.name === "Abu Chemical Partners 078"
        ? { ...s, sector: "BANANAS" as unknown as Supplier["sector"] }
        : s
    );
    const ctx: ActionOpsContext = { ...base, suppliers };
    const { threatCard } = runSentinel(ctx);
    const { exposureResults } = runAtlas(ctx, threatCard);

    const corrupted = exposureResults.find(
      (e) => e.supplierName === "Abu Chemical Partners 078"
    );
    expect(corrupted?.sector).toBe("OTHER_UNMAPPED");
    // A clean supplier keeps its valid closed-vocab sector.
    const clean = exposureResults.find(
      (e) => e.supplierName === "Eastern Energy Partners 094"
    );
    expect(clean?.sector).toBe("ENERGY");
  });

  it("declares no-direct-exposure for a genuinely unmatched event (zero-exposure control)", () => {
    const base = hormuzContext();
    // A scenario whose match targets a country with no supplier in the base.
    const emptyScenario: ActionOpsScenario = {
      ...base.scenario,
      id: "SCN-EMPTY-TEST",
      match: { countries: ["ZZ"] }
    };
    const ctx: ActionOpsContext = { ...base, scenario: emptyScenario };
    const { threatCard } = runSentinel(ctx);
    const { exposureResults, dataGaps } = runAtlas(ctx, threatCard);

    expect(exposureResults).toEqual([]);
    expect(dataGaps.join(" ")).toMatch(/no direct exposure/i);
  });

  it("fails the packet CLOSED on a rejected handoff: the gatekeeper BLOCKS, not just a flag", () => {
    const ctx = hormuzContext();
    const { threatCard, agentRun: sentinelRun } = runSentinel(ctx);
    const misclassified = {
      ...threatCard,
      location: { ...threatCard.location, chokepoint: "Strait of Malacca" }
    };
    const { exposureResults, agentRun: atlasRun } = runAtlas(ctx, misclassified);
    expect(atlasRun.validationStatus).toBe("FAIL");

    // The teeth of the firewall: without the gatekeeper acting on the FAIL, the
    // rejection would be cosmetic and the packet still approvable. A FAILED agent
    // must hold the packet (do-no-harm).
    const gatekeeper = runActionOpsGatekeeper({
      suppliers: ctx.suppliers,
      threatCard: misclassified,
      exposureResults,
      supplierMessages: [],
      agentRuns: [sentinelRun, atlasRun],
      checkedAt: ctx.baseDateIso
    });
    expect(gatekeeper.status).toBe("BLOCKED");
    expect(gatekeeper.approvedForHumanReview).toBe(false);
  });

  it("matches the chokepoint scope case- and whitespace-insensitively", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // Whitespace/casing drift must NOT skip the firewall: a padded/recased Hormuz still
    // resolves to the Gulf scope, so the Gulf match validates and yields nine exposures.
    const padded = {
      ...threatCard,
      location: { ...threatCard.location, chokepoint: "  Strait of HORMUZ  " }
    };
    const { exposureResults, agentRun } = runAtlas(ctx, padded);
    expect(exposureResults).toHaveLength(9);
    expect(agentRun.validationStatus).toBe("PASS");
  });

  it("fails closed when the threat claims a chokepoint with no known scope", () => {
    const ctx = hormuzContext();
    const { threatCard } = runSentinel(ctx);
    // An unmapped chokepoint cannot be validated; emitting exposures on an
    // unverifiable threat would be the silent-bypass hole, so Atlas fails closed.
    const unmapped = {
      ...threatCard,
      location: { ...threatCard.location, chokepoint: "Bab el-Mandeb" }
    };
    const { exposureResults, dataGaps, agentRun } = runAtlas(ctx, unmapped);
    expect(exposureResults).toEqual([]);
    expect(dataGaps.join(" ")).toMatch(/no known affected scope/i);
    expect(agentRun.validationStatus).toBe("FAIL");
  });

  it("drives the empty-exposure cascade through the full agent run without throwing", async () => {
    const base = hormuzContext();
    const emptyScenario: ActionOpsScenario = {
      ...base.scenario,
      id: "SCN-EMPTY-E2E",
      match: { countries: ["ZZ"] }
    };
    // Real cached signals so the Verifier corroborates -- a 0-signal run is a genuine
    // verification FAIL that WOULD block (the do-no-harm gate working, asserted via the
    // rejection test above). This isolates the empty-EXPOSURE cascade: a no-match flows
    // through Simulator/Strategist/Dispatcher/gatekeeper with empty exposures and must
    // not throw. It is an HONEST zero-exposure packet (not a failure), so every agent
    // stays PASS and the gatekeeper does NOT block it -- distinct from the rejected
    // (FAIL) handoff above.
    const signals = await fetchPublicSignals({ useLive: false });
    const result = await runActionOpsAgents({ ...base, scenario: emptyScenario, signals });
    expect(result.exposureResults).toEqual([]);
    expect(result.dataGaps.join(" ")).toMatch(/no direct exposure/i);
    expect(result.playbooks).toEqual([]);
    expect(result.supplierMessages).toEqual([]);
    expect(result.actionItems).toEqual([]);
    expect(result.gatekeeper.status).not.toBe("BLOCKED");
    expect(result.agentRuns.every((r) => r.validationStatus === "PASS")).toBe(true);
  });
});
