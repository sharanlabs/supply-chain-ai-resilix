// D.8 cost ledger (R4-10). key-OFF, NO network in any test here. Five things are proven:
//   (1) the cost MATH against HAND-PINNED absolute dollar values (re-derived by hand,
//       NOT generated by costUsd -- a self-checking test would pass even if the formula
//       were wrong).
//   (2) FAIL-LOUD on an unknown model (the guard the budget cap leans on); coercion of
//       undefined provider token counts to 0 (no throw, no NaN).
//   (3) the BUDGET HARD-STOP blocks a would-breach call and allows an under-cap one,
//       DI'd with injected spent/next (no network, no spend).
//   (4) the key-OFF packet carries totalCostUsd 0 + a stamped pricingVersion.
//   (5) BACK-COMPAT: a pre-D.8 stored agentRun (no ledger fields) and a pre-D.8 V2
//       packet (no cost summary) both still parse.

const BASE_DATE = "2026-06-18T12:00:00.000Z";

function hormuzContext(): ActionOpsContext {
  return {
    scenario: getActionOpsScenario(),
    signals: [],
    suppliers: ingestSeed().suppliers,
    baseDateIso: BASE_DATE
  };
}

describe("D.8 pricing table + cost formula (hand-pinned, R4-10)", () => {
  it("pins the GA price list and version (the contract the costs are computed against)", () => {
    // The version + prices are the load-bearing contract. Pinned literally so a silent
    // re-price (which would retroactively change stored costs) fails this test loudly.
    expect(PRICING_VERSION).toBe("2026-06-22");
    expect(GEMINI_PRICING["gemini-2.5-flash"]).toEqual({
      inputPerMillionUsd: 0.3,
      outputPerMillionUsd: 2.5
    });
    expect(GEMINI_PRICING["gemini-2.5-flash-lite"]).toEqual({
      inputPerMillionUsd: 0.1,
      outputPerMillionUsd: 0.4
    });
    expect(GEMINI_PRICING["gemini-2.5-pro"]).toEqual({
      inputPerMillionUsd: 1.25,
      outputPerMillionUsd: 10
    });
  });

  it("computes flash cost = $1.55 for 1M input + 500k output (HAND-PINNED, not generated)", () => {
    // Re-derived BY HAND: 1,000,000/1e6 * 0.30 + 500,000/1e6 * 2.50
    //                   =        1.0 * 0.30 +        0.5 * 2.50
    //                   =            0.30    +         1.25      = 1.55
    expect(costUsd("gemini-2.5-flash", 1_000_000, 500_000)).toBeCloseTo(1.55, 10);
  });

  it("computes flash-lite cost = $0.60 for 2M input + 1M output (HAND-PINNED)", () => {
    // BY HAND: 2,000,000/1e6 * 0.10 + 1,000,000/1e6 * 0.40 = 0.20 + 0.40 = 0.60
    expect(costUsd("gemini-2.5-flash-lite", 2_000_000, 1_000_000)).toBeCloseTo(0.6, 10);
  });

  it("computes pro cost = $1.50 for 400k input + 100k output (HAND-PINNED)", () => {
    // BY HAND: 400,000/1e6 * 1.25 + 100,000/1e6 * 10 = 0.50 + 1.00 = 1.50
    expect(costUsd("gemini-2.5-pro", 400_000, 100_000)).toBeCloseTo(1.5, 10);
  });

  it("prices zero tokens at $0 (a no-token but real-model call still resolves)", () => {
    expect(costUsd("gemini-2.5-flash", 0, 0)).toBe(0);
  });

  it("tolerates the models/ prefix Google ListModels returns (no false unknown-model)", () => {
    // AgentRun.model is the bare id, but a prefixed id must still key the table.
    expect(costUsd("models/gemini-2.5-flash", 1_000_000, 500_000)).toBeCloseTo(1.55, 10);
  });

  it("FAILS LOUD on an unknown model -- never silently prices at $0", () => {
    // The whole point: a $0 cost on a real billed call is the blind spot the budget cap
    // would never catch. A typo'd / retired live id throws instead of pricing at 0.
    expect(() => costUsd("gemini-9.9-omega", 1_000, 1_000)).toThrow(/unknown model/i);
    // The deterministic sentinel value is NOT in the table -- so the deterministic path
    // must NEVER call costUsd with it (it stamps 0 directly). Prove it would throw if it did.
    expect(() => costUsd("deterministic-rules", 0, 0)).toThrow(/unknown model/i);
  });

  it("coerces undefined provider token counts to 0 (no throw, no NaN on a real model)", () => {
    // The AI SDK reports usage fields as number | undefined; a successful call can still
    // hand us undefined counts. The loud guard is on the MODEL, not the token count.
    expect(costUsd("gemini-2.5-flash", undefined, undefined)).toBe(0);
    expect(costUsd("gemini-2.5-flash", 1_000_000, undefined)).toBeCloseTo(0.3, 10);
    expect(Number.isNaN(costUsd("gemini-2.5-flash", undefined, 500_000))).toBe(false);
  });
});

describe("D.8 budget hard-stop (fail-closed, DI, no network)", () => {
  it("uses the Success_Criteria $5 cap as the default", () => {
    expect(DEFAULT_BUDGET_CAP_USD).toBe(5);
  });

  it("ALLOWS an under-cap call (spent + next <= cap)", () => {
    // $4.00 spent + a $0.50 next call = $4.50, under $5 -> no throw.
    expect(() => assertWithinBudget(4.0, 0.5, 5)).not.toThrow();
    // Exactly at the cap is allowed (cap is the ceiling, not a strict-less bound).
    expect(() => assertWithinBudget(4.5, 0.5, 5)).not.toThrow();
  });

  it("BLOCKS a would-breach call BEFORE it can bill (spent + next > cap)", () => {
    // $4.90 spent + a $0.20 next call = $5.10 > $5 -> throws, call never made.
    expect(() => assertWithinBudget(4.9, 0.2, 5)).toThrow(BudgetExceededError);
  });

  it("fails CLOSED on a non-finite cost input (blocks rather than passes blindly)", () => {
    expect(() => assertWithinBudget(Number.NaN, 0.5, 5)).toThrow(BudgetExceededError);
    expect(() => assertWithinBudget(1, Number.POSITIVE_INFINITY, 5)).toThrow(BudgetExceededError);
  });

  it("liveGenerateObject runs the guard BEFORE the injected call -- a breach never calls generate", async () => {
    // The hard-stop boundary: with spent+next over cap, the budget guard throws and the
    // injected generate (the would-be billable call) is NEVER invoked. This proves the
    // breach cannot bill, with zero network.
    let generateCalled = false;
    await expect(
      liveGenerateObject({
        model: "gemini-2.5-flash",
        schema: AgentRunSchema, // any schema; the call is blocked before it is used
        prompt: "noop",
        budget: { spentUsd: 4.95, estimatedNextUsd: 0.2, capUsd: 5 },
        generate: async () => {
          generateCalled = true;
          return { object: {} };
        }
      })
    ).rejects.toBeInstanceOf(BudgetExceededError);
    expect(generateCalled).toBe(false);
  });

  it("liveGenerateObject proceeds under cap and threads the injected usage through", async () => {
    // Under cap: the call runs and the provider-reported usage comes back for costUsd.
    const out = await liveGenerateObject({
      model: "gemini-2.5-flash",
      schema: AgentRunSchema,
      prompt: "noop",
      budget: { spentUsd: 0, estimatedNextUsd: 0.1, capUsd: 5 },
      generate: async () => ({
        object: { ok: true },
        usage: { inputTokens: 1000, outputTokens: 500, totalTokens: 1500, finishReason: "stop" }
      })
    });
    expect(out.object).toEqual({ ok: true });
    expect(out.usage).toEqual({
      inputTokens: 1000,
      outputTokens: 500,
      totalTokens: 1500,
      finishReason: "stop"
    });
  });
});

describe("D.8 ledger fields on the AgentRun (R4-10)", () => {
  it("a deterministic run stamps cost 0, finishReason deterministic, and the pricing version", () => {
    const run = makeAgentRun({
      id: "RUN-X",
      agentName: "Test",
      input: { a: 1 },
      output: { b: 2 },
      summary: "deterministic run",
      createdAt: BASE_DATE
    });
    // The deterministic path never consults the pricing table (model is the unknown
    // "deterministic-rules"); it stamps 0 DIRECTLY -- so a $0 deterministic run is NOT a
    // mispriced live call, and the table's unknown-model guard stays a real live guard.
    expect(run.model).toBe("deterministic-rules");
    expect(run.costUsd).toBe(0);
    expect(run.inputTokens).toBe(0);
    expect(run.outputTokens).toBe(0);
    expect(run.totalTokens).toBe(0);
    expect(run.finishReason).toBe("deterministic");
    expect(run.errorClass).toBeNull();
    expect(run.pricingVersion).toBe(PRICING_VERSION);
  });

  it("a live run prices the reported usage with costUsd (HAND-PINNED $1.55)", () => {
    const run = makeAgentRun({
      id: "RUN-LIVE",
      agentName: "Test",
      input: {},
      output: {},
      summary: "live run",
      createdAt: BASE_DATE,
      model: "gemini-2.5-flash",
      mode: "LIVE_AI",
      usage: { inputTokens: 1_000_000, outputTokens: 500_000, totalTokens: 1_500_000, finishReason: "stop" }
    });
    // Same hand-pinned 1M+500k flash math as above -- the ledger field carries the dollars.
    expect(run.costUsd).toBeCloseTo(1.55, 10);
    expect(run.finishReason).toBe("stop");
    expect(run.pricingVersion).toBe(PRICING_VERSION);
  });
});

describe("D.8 packet-level cost summary (R4-10, key-OFF)", () => {
  it("summarizeCost sums per-run costs and stamps the pricing version", () => {
    const runs = [
      makeAgentRun({
        id: "R1",
        agentName: "A",
        input: {},
        output: {},
        summary: "live",
        createdAt: BASE_DATE,
        model: "gemini-2.5-flash",
        mode: "LIVE_AI",
        usage: { inputTokens: 1_000_000, outputTokens: 500_000, totalTokens: 1_500_000 }
      }),
      makeAgentRun({
        id: "R2",
        agentName: "B",
        input: {},
        output: {},
        summary: "det",
        createdAt: BASE_DATE
      })
    ];
    const summary = summarizeCost(runs);
    // $1.55 (live flash) + $0 (deterministic) = $1.55.
    expect(summary.totalCostUsd).toBeCloseTo(1.55, 10);
    expect(summary.pricingVersion).toBe(PRICING_VERSION);
  });

  it("the key-OFF Hormuz packet has totalCostUsd 0 + a stamped pricingVersion", async () => {
    const packet = await buildDecisionPacket({ useLiveSignals: false });
    // Every agent ran deterministic (no live call) -> zero spend, but the version is
    // still stamped so the packet is self-describing about WHICH price list applied.
    expect(packet.totalCostUsd).toBe(0);
    expect(packet.pricingVersion).toBe(PRICING_VERSION);
    // Every run carries a 0 cost (none priced via the table).
    expect(packet.agentRuns.every((r) => r.costUsd === 0)).toBe(true);
  });
});

describe("D.8 live-path cost threading (DI, key-OFF behavior, no network)", () => {
  it("a budget-breach DI on classifyThreatLive degrades and records BUDGET_EXCEEDED", async () => {
    // Force the live path on but with a budget already at the cap, so the hard-stop
    // throws inside liveGenerateObject and the agent falls back deterministically. The
    // injected generate must NEVER be called (the breach blocks before it).
    let generateCalled = false;
    const { agentRun } = await classifyThreatLive(hormuzContext(), {
      enabled: () => true,
      budget: { spentUsd: 5, estimatedNextUsd: 0.5, capUsd: 5 },
      generate: async () => {
        generateCalled = true;
        return { object: {} };
      }
    });
    expect(generateCalled).toBe(false);
    expect(agentRun.mode).toBe("FAILED_TO_FALLBACK");
    expect(agentRun.errorClass).toBe("BUDGET_EXCEEDED");
    // A blocked call billed nothing -> 0 cost, but the run is still ledgered, not absent.
    expect(agentRun.costUsd).toBe(0);
    expect(agentRun.pricingVersion).toBe(PRICING_VERSION);
  });

  it("a clean live result threads the reported usage into a real costUsd", async () => {
    const { agentRun } = await classifyThreatLive(hormuzContext(), {
      enabled: () => true,
      budget: { spentUsd: 0, estimatedNextUsd: 0.1, capUsd: 5 },
      generate: async () => ({
        object: {
          eventType: "CHOKEPOINT_CLOSURE",
          severity: "HIGH",
          location: { chokepoint: "Strait of Hormuz" },
          summary: "Strait of Hormuz transit disrupted.",
          evidenceUrls: [
            "https://api.gdeltproject.org/api/v2/doc/doc?query=Strait+of+Hormuz&mode=artlist&format=json"
          ],
          confidence: 0.8
        },
        usage: { inputTokens: 1_000_000, outputTokens: 500_000, totalTokens: 1_500_000, finishReason: "stop" }
      })
    });
    expect(agentRun.mode).toBe("LIVE_AI");
    // The reported 1M+500k usage priced at the hand-pinned flash $1.55.
    expect(agentRun.costUsd).toBeCloseTo(1.55, 10);
    expect(agentRun.inputTokens).toBe(1_000_000);
    expect(agentRun.finishReason).toBe("stop");
  });
});

describe("D.8 back-compat (additive fields, no break to stored shapes)", () => {
  it("a pre-D.8 stored agentRun (no ledger fields) still parses", () => {
    // Exactly the AgentRun shape that persisted before D.8: no inputTokens/costUsd/etc.
    const preD8Run = {
      id: "RUN-legacy",
      agentName: "Legacy Agent",
      model: "deterministic-rules",
      mode: "DETERMINISTIC_RULES",
      latencyMs: 0,
      tokenEstimate: 12,
      inputHash: "in",
      outputHash: "out",
      validationStatus: "PASS",
      summary: "a run from before the cost ledger",
      createdAt: BASE_DATE
    };
    const parsed = AgentRunSchema.parse(preD8Run);
    // The new fields stay ABSENT (.optional() does not inject defaults) -- so a strict
    // round-trip of an old packet is byte-identical, which the versioning tests rely on.
    expect(parsed).toEqual(preD8Run);
    expect("costUsd" in parsed).toBe(false);
    expect("pricingVersion" in parsed).toBe(false);
  });

  it("a pre-D.8 V2 packet (no cost summary) still parses round-trip-identical", () => {
    // makeV2Packet predates D.8 (agentRuns: [], no totalCostUsd/pricingVersion). It must
    // parse through parseStoredPacket unchanged -- the additive summary fields stay absent.
    const preD8Packet = makeV2Packet();
    const restored = parseStoredPacket(preD8Packet);
    expect(restored).toEqual(preD8Packet);
    expect("totalCostUsd" in restored).toBe(false);
    expect("pricingVersion" in restored).toBe(false);
  });
});
